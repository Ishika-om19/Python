#Print Natural No From 1 to 10

print("Natural number from 1 to 10")
for x in range(1,11):
    print(x)
print("Even Number between 1 to 10")
for z in range(2,11,2):
    print(z)
print("Odd Number between 1 to 10")
for y in range(1,10,2):
    print(y)
print("Reverse Odd between 10 to 1")
for k in range(9,0 ,-2):
    print(k)
